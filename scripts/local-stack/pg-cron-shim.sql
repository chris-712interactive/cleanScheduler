-- Stand-in for migration 0021 when the pg_cron extension package is not installed.
-- The expire function from 0020 is unchanged. No hourly job is actually scheduled.
-- The Supabase database image includes pg_cron, so CI uses the real migration.

create schema if not exists cron;

create table if not exists cron.job (
  jobid bigint generated by default as identity primary key,
  jobname text unique,
  schedule text,
  command text
);

create or replace function cron.unschedule(job_id bigint)
returns boolean
language sql
as $$
  select true;
$$;

create or replace function cron.schedule(job_name text, schedule text, command text)
returns bigint
language plpgsql
as $$
declare
  new_id bigint;
begin
  insert into cron.job (jobname, schedule, command)
  values (job_name, schedule, command)
  on conflict (jobname) do update
    set schedule = excluded.schedule,
        command = excluded.command
  returning jobid into new_id;
  return new_id;
end;
$$;

grant usage on schema cron to postgres;
grant all privileges on all tables in schema cron to postgres;
grant execute on function public.expire_sent_quotes_past_valid_until() to postgres;

select cron.unschedule(j.jobid)
from cron.job j
where j.jobname = 'expire_sent_quotes_past_valid_until';

select cron.schedule(
  'expire_sent_quotes_past_valid_until',
  '0 * * * *',
  $$select public.expire_sent_quotes_past_valid_until();$$
);
